import { test, expect } from '@playwright/test'

test('a new user can add a person and their reminder without losing context', async ({
  page
}, testInfo) => {
  const email = `flow-${testInfo.project.name}-${Date.now()}@example.test`
  await page.request.post('/api/users', { data: { email, password: 'flow test password' } })
  await page.goto('/login')
  await page.getByLabel('email', { exact: true }).fill(email)
  await page.getByLabel('password', { exact: true }).fill('flow test password')
  await page.getByRole('button', { name: 'Submit' }).click()
  await expect(page).toHaveURL(/\/reachout$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Add reminder', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Create Reachout' })).toBeDisabled()
  await page.getByRole('link', { name: 'Contacts page' }).click()
  await page.getByRole('button', { name: 'Add your first contact', exact: true }).click()
  await page.getByLabel('New FirstName', { exact: true }).fill('Sam')
  await page.getByRole('button', { name: 'Create Contact' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('article')).toContainText('No reminders yet')
  await page.getByRole('link', { name: 'Add their first reminder' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('New ContactID')).not.toHaveValue('')
  await expect(page.getByRole('dialog')).toContainText('We email you a reminder to contact Sam.')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page).toHaveURL(/\/reachout$/)
  await page.reload()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/contact')
  await page.getByRole('article').getByRole('link', { name: 'Add reminder' }).click()
  await page.getByLabel('New Frequency').selectOption('7d')
  await page.getByLabel('New StartDate').fill('2030-02-01')
  await page.getByRole('button', { name: 'Create Reachout' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('article')).toContainText('Next email:')
  await expect(page.getByRole('article')).toContainText('2030')
  await expect(page.getByRole('article')).not.toContainText('unavailable')
  await page.getByRole('button', { name: 'Pause reminder' }).click()
  await expect(page.getByRole('article')).toContainText('No emails while paused.')
  await page.goto('/contact')
  await expect(page.getByRole('article')).toContainText('1 paused')
})
